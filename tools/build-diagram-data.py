"""Regenerates js/diagram-data.js from the project's diagrams/*.mermaid files.

Usage:   python tools/build-diagram-data.py [path-to-diagrams-folder]
Default: the repo's diagrams/ folder, found from this script's location
         (marsvin-web/DocumentationInformation/data-flow-animation/tools/ -> repo root).

To add a diagram: put NAME.mermaid in the diagrams folder, add a line to META below, run this script.
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DIAGRAMS = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(
    os.path.join(HERE, '..', '..', '..', '..', 'diagrams'))
OUT = os.path.join(HERE, '..', 'js', 'diagram-data.js')

# (group, file name without .mermaid, title, description)
META = [
    ('Structure', 'marsvin-er-diagram', 'ER diagram', 'The 15 database tables and how they relate.'),
    ('Structure', 'marsvin-domain-model', 'Domain model', 'Class diagram of the entities and enums.'),
    ('Structure', 'marsvin-class-services', 'Services and stores', 'Class diagram of the stores, their interfaces and DI lifetimes (incl. JWT classes).'),
    ('Structure', 'marsvin-dfd', 'Data flow diagram', 'Processes, data stores and trust boundaries (basis for the STRIDE table).'),
    ('Structure', 'marsvin-navigation', 'Navigation and access control', 'Which pages exist and who may open them (incl. /api and the admin dashboard).'),
    ('Structure', 'marsvin-deployment', 'Deployment', 'What runs where: browser, web app, SQL Server, SMTP, reCAPTCHA.'),
    ('Sequence', 'marsvin-sequence-register', 'Register', 'Sign-up with reCAPTCHA, password policy and e-mail confirmation.'),
    ('Sequence', 'marsvin-sequence-login', 'Login', 'Password, then e-mail link or TOTP, lockout and security events.'),
    ('Sequence', 'marsvin-sequence-password-reset', 'Forgot / reset password', 'Single-use token by e-mail and the new password.'),
    ('Sequence', 'marsvin-sequence-totp-enrollment', '2FA enrol / disable', 'Authenticator app setup with the encrypted secret.'),
    ('Sequence', 'marsvin-sequence-session-check', 'Session check', 'What is verified on every request (security stamp, timeouts).'),
    ('Sequence', 'marsvin-sequence-add-to-cart', 'Add to cart', 'Guest cart in session, account cart in SQL.'),
    ('Sequence', 'marsvin-sequence-checkout', 'Checkout', 'Transaction, stock locking, order and order lines (guest or customer).'),
    ('Sequence', 'marsvin-sequence-order-status', 'Order status and cancelling', 'How staff move an order forward, and cancelling.'),
    ('Sequence', 'marsvin-sequence-donation', 'Donation', 'A demo donation and its thank-you e-mail.'),
    ('Sequence', 'marsvin-sequence-chat', 'Support chat (Pip)', 'How the chat assistant answers.'),
    ('Sequence', 'marsvin-sequence-jwt-api', 'JWT API', 'Getting a token and using it on /api.'),
    ('Sequence', 'marsvin-sequence-admin-edit', 'Admin edit with audit log', 'A staff change and its AuditLog entry.'),
    ('Sequence', 'marsvin-sequence-inactivity-cleanup', 'GDPR inactivity cleanup', 'Warning e-mails and automatic account deletion.'),
    ('Activity and state', 'marsvin-activity-checkout', 'Activity: checkout', 'Checkout as an activity diagram.'),
    ('Activity and state', 'marsvin-activity-email-language', 'Activity: e-mail language', 'Which language an e-mail is written in.'),
    ('Activity and state', 'marsvin-state-animal', 'State: animal', 'Available, reserved, sold, not for sale.'),
    ('Activity and state', 'marsvin-state-order', 'State: order', 'Placed, processing, sent, delivered, cancelled.'),
    ('Course models', 'marsvin-ssd-place-order', 'System sequence diagram', 'SSD for “place order”.'),
    ('Course models', 'marsvin-communication-checkout', 'Communication diagram', 'Checkout as a communication diagram.'),
]

items = []
for group, name, title, desc in META:
    with open(os.path.join(DIAGRAMS, name + '.mermaid'), encoding='utf8') as f:
        src = f.read()
    items.append({'id': name, 'group': group, 'title': title, 'desc': desc, 'src': src})

with open(OUT, 'w', encoding='utf8', newline='\n') as f:
    f.write("// GENERATED by tools/build-diagram-data.py from the repo's diagrams/*.mermaid files - do not edit by hand.\n")
    f.write('const DG_DATA = ' + json.dumps(items, ensure_ascii=False) + ';\n')
print('wrote', len(items), 'diagrams to', os.path.normpath(OUT))
