"""Regenerates js/doc-data.js (the Documentation dropdown) from the real Marsvin repo on GitHub.

Usage:   python tools/build-doc-data.py
To add a document: add a line to DOCS below and run the script.
"""
import json, os, urllib.request

REPO = 'https://raw.githubusercontent.com/Elvie-Abarth/Esti-whent-creazy-whit-the-protject/master/'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'js', 'doc-data.js')

# (group, repo path, title)
DOCS = [
    ('Start', 'START-HERE.txt', 'Start here'),
    ('Start', 'README.md', 'Project README'),
    ('Start', 'marsvin-web/README.md', 'Web app README'),
    ('Architecture', 'marsvin-web/DocumentationInformation/WEBSITE-ARCHITECTURE.md', 'Website architecture'),
    ('Architecture', 'marsvin-web/DocumentationInformation/DATABASE-ARCHITECTURE.md', 'Database architecture'),
    ('Architecture', 'marsvin-web/DocumentationInformation/DATABASE-CREATION-SCRIPT.md', 'Database creation script'),
    ('Notes', 'marsvin-web/DocumentationInformation/DATABASE-NOTES.txt', 'Database notes'),
    ('Notes', 'marsvin-web/DocumentationInformation/SECURITY-NOTES.txt', 'Security notes'),
    ('Notes', 'marsvin-web/DocumentationInformation/JWT-NOTES.txt', 'JWT notes'),
    ('Diagrams', 'diagrams/marsvin-diagrams.md', 'Diagram descriptions'),
]

out = []
for group, path, title in DOCS:
    with urllib.request.urlopen(REPO + path, timeout=30) as r:
        text = r.read().decode('utf-8')
    out.append({'id': path.replace('/', '_'), 'group': group, 'title': title, 'path': path,
                'md': path.lower().endswith('.md'), 'text': text})
    print('ok  ', path, len(text))

with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// GENERATED by tools/build-doc-data.py from the real Marsvin repo - do not edit by hand.\n')
    f.write('const DOC_DATA = ' + json.dumps(out, ensure_ascii=False) + ';\n')
print('wrote', os.path.normpath(OUT))
